using System.Text.RegularExpressions;
using AgenticAIDemo.Models;

namespace AgenticAIDemo.Services;

/// <summary>
/// Simple offline brain when no Gemini API key is set.
/// Uses keyword matching to demonstrate the agent loop without internet.
/// </summary>
public sealed class LocalFallbackService
{
    public GeminiDecision GetNextStep(string userQuestion, List<AgentStep> previousSteps)
    {
        var question = userQuestion.ToLowerInvariant();
        var alreadyQueried = previousSteps.Any(s => s.Action == "run_sql");

        if (!alreadyQueried)
        {
            var sql = BuildSqlFromQuestion(question);
            return new GeminiDecision
            {
                Thought = "I need real data from SQL Server before I can answer.",
                Action = "run_sql",
                ActionInput = sql
            };
        }

        var lastObservation = previousSteps.LastOrDefault(s => s.Observation != null)?.Observation ?? "";
        return new GeminiDecision
        {
            Thought = "I have database results. I can now answer the user.",
            Action = "answer_user",
            ActionInput = $"Based on the database:\n{lastObservation}\n\n(This answer was generated by the local fallback mode.)"
        };
    }

    private static string BuildSqlFromQuestion(string question)
    {
        if (question.Contains("gold"))
        {
            return "SELECT CustomerId, FullName, City, Membership FROM Customers WHERE Membership = 'Gold'";
        }

        if (question.Contains("silver"))
        {
            return "SELECT CustomerId, FullName, City, Membership FROM Customers WHERE Membership = 'Silver'";
        }

        if (question.Contains("city") || question.Contains("cities"))
        {
            return "SELECT City, COUNT(*) AS CustomerCount FROM Customers GROUP BY City ORDER BY CustomerCount DESC";
        }

        if (question.Contains("total") || question.Contains("sales") || question.Contains("revenue") || question.Contains("spent"))
        {
            return "SELECT SUM(Amount) AS TotalSales FROM Orders";
        }

        if (question.Contains("how many") && question.Contains("customer"))
        {
            return "SELECT COUNT(*) AS TotalCustomers FROM Customers";
        }

        if (question.Contains("order"))
        {
            return "SELECT TOP 10 o.OrderId, c.FullName, o.ProductName, o.Amount, o.OrderDate FROM Orders o JOIN Customers c ON o.CustomerId = c.CustomerId ORDER BY o.OrderDate DESC";
        }

        if (question.Contains("more than") || question.Contains("over"))
        {
            var match = Regex.Match(question, @"(\d+)");
            var amount = match.Success ? match.Groups[1].Value : "500";
            return $"SELECT c.FullName, SUM(o.Amount) AS TotalSpent FROM Customers c JOIN Orders o ON c.CustomerId = o.CustomerId GROUP BY c.FullName HAVING SUM(o.Amount) > {amount}";
        }

        return "SELECT TOP 10 c.FullName, c.City, c.Membership, o.ProductName, o.Amount FROM Customers c LEFT JOIN Orders o ON c.CustomerId = o.CustomerId";
    }
}
